CREATE TABLE authors
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    biography  TEXT
);

CREATE TABLE genres
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE books
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    isbn             VARCHAR(20)  NOT NULL UNIQUE,
    description      TEXT,
    publication_year INTEGER
);

CREATE INDEX idx_books_title ON books (title);
CREATE INDEX idx_books_isbn ON books (isbn);

CREATE TABLE book_authors
(
    book_id   BIGINT NOT NULL,
    author_id BIGINT NOT NULL,

    PRIMARY KEY (book_id, author_id),

    CONSTRAINT fk_book_authors_book
        FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,

    CONSTRAINT fk_book_authors_author
        FOREIGN KEY (author_id) REFERENCES authors (id) ON DELETE CASCADE
);

CREATE TABLE book_genres
(
    book_id  BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,

    PRIMARY KEY (book_id, genre_id),

    CONSTRAINT fk_book_genres_book
        FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,

    CONSTRAINT fk_book_genres_genre
        FOREIGN KEY (genre_id) REFERENCES genres (id) ON DELETE CASCADE
);

CREATE TABLE book_copies
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_number VARCHAR(100) NOT NULL UNIQUE,
    status           VARCHAR(30)  NOT NULL DEFAULT 'AVAILABLE',
    book_id          BIGINT       NOT NULL,
    version          BIGINT,

    CONSTRAINT fk_book_copies_book
        FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE INDEX idx_book_copies_book_id
    ON book_copies (book_id);

CREATE INDEX idx_book_copies_status
    ON book_copies (status);

CREATE TABLE loans
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      VARCHAR(100) NOT NULL,
    book_copy_id BIGINT       NOT NULL,
    borrowed_at  TIMESTAMPTZ  NOT NULL,
    due_date     TIMESTAMPTZ  NOT NULL,
    returned_at  TIMESTAMPTZ,
    status       VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT fk_loans_book_copy
        FOREIGN KEY (book_copy_id) REFERENCES book_copies (id)
);

CREATE INDEX idx_loans_user_id ON loans (user_id);
CREATE INDEX idx_loans_status ON loans (status);
CREATE INDEX idx_loans_due_date ON loans (due_date);
CREATE INDEX idx_loans_book_copy_id ON loans (book_copy_id);
